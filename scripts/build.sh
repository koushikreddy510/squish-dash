#!/usr/bin/env bash
#
# Local native builds without an EAS account.
#
#   ./scripts/build.sh                       # Android debug APK (the default)
#   ./scripts/build.sh android               # same thing, spelled out
#   ./scripts/build.sh android --release     # Android release APK
#   ./scripts/build.sh android --install     # build, then adb install onto the attached device
#   ./scripts/build.sh ios                   # iOS simulator .app
#   ./scripts/build.sh all --release         # both, Android first
#
# Flags
#   --release       build the release variant (default: debug)
#   --install       hand the artifact to adb / simctl when a target is attached
#   --clean         regenerate android/ or ios/ from app.json (expo prebuild --clean)
#   --skip-checks   skip typecheck + lint + tests
#   --help          this text
#
# Environment
#   BUILD_ARCHITECTURES=arm64-v8a   build one ABI instead of all four. The CMake
#                                  stage dominates build time, so this roughly
#                                  halves a cold build; arm64-v8a covers every
#                                  modern phone.
#
# android/ and ios/ are generated by `expo prebuild` and are gitignored. Never
# hand-edit them — change app.json or the plugins and regenerate, otherwise the
# change is silently lost the next time anyone runs this script with --clean.

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

PLATFORM=""
VARIANT="debug"
INSTALL=0
CLEAN=0
SKIP_CHECKS=0
START=$SECONDS

step() { printf '\n==> %s\n' "$*"; }
info() { printf '    %s\n' "$*"; }
ok()   { printf '    ok: %s\n' "$*"; }
warn() { printf '    warning: %s\n' "$*" >&2; }
die()  { printf '\nerror: %s\n' "$*" >&2; exit 1; }

usage() {
  awk 'NR > 1 && /^#/ { sub(/^# ?/, ""); print; next } NR > 1 { exit }' "${BASH_SOURCE[0]}"
}

# ---------------------------------------------------------------- preflight--

java_major() {
  "$1/bin/java" -version 2>&1 | head -1 |
    sed -E 's/.*version "([^"]+)".*/\1/' | cut -d. -f1
}

# Newest is not best here: the Android Gradle Plugin fails on a too-new JDK with
# "Unsupported class file major version", so collect every JDK we can find and
# let ensure_java pick a supported one.
java_home_candidates() {
  local found
  if [[ -n "${JAVA_HOME:-}" ]]; then printf '%s\n' "$JAVA_HOME"; fi
  printf '%s\n' \
    "/opt/homebrew/opt/openjdk@21/libexec/openjdk.jdk/Contents/Home" \
    "/opt/homebrew/opt/openjdk@17/libexec/openjdk.jdk/Contents/Home" \
    "/usr/local/opt/openjdk@21/libexec/openjdk.jdk/Contents/Home" \
    "/usr/local/opt/openjdk@17/libexec/openjdk.jdk/Contents/Home" \
    "$HOME/.sdkman/candidates/java/current" \
    "/Applications/Android Studio.app/Contents/jbr/Contents/Home"
  for found in 21 17; do
    found="$(/usr/libexec/java_home -v "$found" 2>/dev/null || true)"
    if [[ -n "$found" ]]; then printf '%s\n' "$found"; fi
  done
}

ensure_java() {
  local requested="${JAVA_HOME:-}" home major best="" best_major=""
  while IFS= read -r home; do
    [[ -n "$home" && -x "$home/bin/java" ]] || continue
    major="$(java_major "$home")"
    [[ "$major" =~ ^[0-9]+$ ]] || continue
    if (( major >= 17 && major <= 21 )); then
      best="$home"
      best_major="$major"
      break
    fi
    if [[ -z "$best" ]]; then
      best="$home"
      best_major="$major"
    fi
  done < <(java_home_candidates)

  [[ -n "$best" ]] || die "no JDK found. Install one with: brew install openjdk@21"
  if (( best_major < 17 || best_major > 21 )); then
    die "only found Java $best_major at $best, but the Android Gradle Plugin needs 17-21.
    Install a supported one with:  brew install openjdk@21"
  fi

  if [[ -n "$requested" && "$requested" != "$best" ]]; then
    info "Java $best_major at $best, overriding JAVA_HOME=$requested (unsupported by AGP)"
  fi
  export JAVA_HOME="$best"
  export PATH="$JAVA_HOME/bin:$PATH"
  ok "java $best_major ($JAVA_HOME)"
}

android_sdk() {
  local candidate
  for candidate in "${ANDROID_HOME:-}" "${ANDROID_SDK_ROOT:-}" \
                   "$HOME/Library/Android/sdk" "$HOME/Android/Sdk" "/usr/local/share/android-sdk"; do
    if [[ -n "$candidate" && -d "$candidate/platform-tools" ]]; then
      printf '%s' "$candidate"
      return 0
    fi
  done
  return 1
}

attached_devices() {
  adb devices 2>/dev/null | awk 'NR > 1 && $2 == "device" { print $1 }'
}

run_checks() {
  step "Quality gate"
  npx tsc --noEmit || die "typecheck failed — fix the types before shipping a build."
  ok "typecheck"
  npx expo lint || die "lint failed."
  ok "lint"
  npx jest --ci --silent || die "tests failed — a build that breaks the reader is not a build."
  ok "tests"
}

prebuild() {
  local platform="$1"
  if [[ -d "$platform" && "$CLEAN" -eq 0 ]]; then
    ok "$platform/ already generated (pass --clean to regenerate from app.json)"
    return
  fi

  step "Prebuild $platform"
  local args=(--platform "$platform" --no-install)
  if (( CLEAN )); then args+=(--clean); fi
  npx expo prebuild "${args[@]}" || die "expo prebuild failed for $platform."
}

# ------------------------------------------------------------------ android--

build_android() {
  step "Android environment"
  local sdk
  sdk="$(android_sdk)" || die "no Android SDK found. Set ANDROID_HOME (it needs a platform-tools/ folder) and re-run."
  export ANDROID_HOME="$sdk"
  export ANDROID_SDK_ROOT="$sdk"
  ok "SDK at $sdk"
  ensure_java
  command -v adb >/dev/null 2>&1 || die "adb is not on PATH (it lives in \$ANDROID_HOME/platform-tools)."

  prebuild android

  local wrapper
  wrapper="$(sed -n 's/^distributionUrl=//p' android/gradle/wrapper/gradle-wrapper.properties)"
  info "wrapper: ${wrapper//\\/} (downloaded on the first run, ~130 MB)"

  local task="assembleDebug"
  if [[ "$VARIANT" == "release" ]]; then task="assembleRelease"; fi

  # Four ABIs is right for an APK you hand to someone; one ABI is right when you
  # are iterating, since the CMake stage dominates the build time.
  local extra=()
  if [[ -n "${BUILD_ARCHITECTURES:-}" ]]; then
    extra+=("-PreactNativeArchitectures=$BUILD_ARCHITECTURES")
    info "architectures: $BUILD_ARCHITECTURES"
  else
    info "architectures: all (set BUILD_ARCHITECTURES=arm64-v8a for faster builds)"
  fi

  step "Gradle $task"
  # macOS still ships bash 3.2, where an empty "${extra[@]}" aborts under set -u;
  # the ${x[@]+...} form only expands when the array has elements.
  ( cd android && ./gradlew "$task" --console=plain ${extra[@]+"${extra[@]}"} ) ||
    die "gradle $task failed. For the full stack, re-run: (cd android && ./gradlew $task --stacktrace)"

  local apk="android/app/build/outputs/apk/$VARIANT/app-$VARIANT.apk"
  if [[ ! -f "$apk" ]]; then
    apk="$(find android/app/build/outputs/apk -name '*.apk' -type f | head -1)"
  fi
  [[ -f "$apk" ]] || die "Gradle succeeded but no APK was found under android/app/build/outputs/apk."

  ok "APK: $ROOT/$apk ($(du -h "$apk" | cut -f1 | tr -d ' '))"

  if [[ "$VARIANT" == "release" ]]; then
    warn "The release APK is signed with the debug keystore (the Expo template default),"
    warn "so it installs fine but cannot go to Play. Configure a real keystore before shipping."
  fi

  if (( INSTALL )); then
    step "Installing"
    local devices
    devices="$(attached_devices)"
    if [[ -z "$devices" ]]; then
      warn "no device or emulator attached — skipping install."
      info "start one, then: adb install -r $ROOT/$apk"
    else
      local device
      for device in $devices; do
        adb -s "$device" install -r "$apk" || die "adb install failed on $device."
        ok "installed on $device"
        if [[ "$VARIANT" == "debug" ]]; then
          adb -s "$device" reverse tcp:8081 tcp:8081 >/dev/null 2>&1 || true
          info "debug builds load JS from Metro — start it with: npx expo start"
        fi
      done
    fi
  fi
}

# ---------------------------------------------------------------------- ios--

build_ios() {
  step "iOS environment"
  command -v xcodebuild >/dev/null 2>&1 || die "xcodebuild not found. Install Xcode, then re-run."
  ok "$(xcodebuild -version | head -1)"
  command -v pod >/dev/null 2>&1 ||
    die "CocoaPods is not installed, and iOS builds cannot start without it.
    Install it with:  brew install cocoapods
    Then re-run:      ./scripts/build.sh ios
    Android is unaffected:  ./scripts/build.sh android"

  prebuild ios

  step "pod install"
  ( cd ios && pod install ) || die "pod install failed — run it by hand in ios/ to see the full error."

  local workspace scheme config
  workspace="$(find ios -maxdepth 1 -name '*.xcworkspace' -type d | head -1)"
  [[ -n "$workspace" ]] || die "no .xcworkspace under ios/ after pod install."
  scheme="$(basename "$workspace" .xcworkspace)"
  config="Debug"
  if [[ "$VARIANT" == "release" ]]; then config="Release"; fi

  step "xcodebuild $config (simulator)"
  # Simulator builds need no signing team, which keeps this runnable on a fresh machine.
  xcodebuild \
    -workspace "$workspace" \
    -scheme "$scheme" \
    -configuration "$config" \
    -sdk iphonesimulator \
    -derivedDataPath ios/build \
    CODE_SIGNING_ALLOWED=NO \
    build ||
    die "xcodebuild failed. Open $workspace in Xcode to see the full log."

  local app
  app="$(find "ios/build/Build/Products/$config-iphonesimulator" -maxdepth 1 -name '*.app' -type d | head -1)"
  [[ -n "$app" ]] || die "xcodebuild succeeded but no .app was found in ios/build/Build/Products."
  ok "APP: $ROOT/$app"

  if (( INSTALL )); then
    step "Installing"
    local bundle_id booted
    bundle_id="$(node -p "require('./app.json').expo.ios.bundleIdentifier" 2>/dev/null || true)"
    booted="$(xcrun simctl list devices booted 2>/dev/null | awk -F'[()]' '/Booted/ { print $2; exit }')"
    if [[ -z "$booted" ]]; then
      warn "no booted simulator — skipping install."
      info "open -a Simulator, then: xcrun simctl install booted $app"
    else
      xcrun simctl install "$booted" "$app" || die "simctl install failed on $booted."
      ok "installed on simulator $booted"
      if [[ -n "$bundle_id" ]]; then
        xcrun simctl launch "$booted" "$bundle_id" >/dev/null || true
        info "launched $bundle_id"
      fi
    fi
  fi
}

# --------------------------------------------------------------------- main--

while [[ $# -gt 0 ]]; do
  case "$1" in
    android | ios | all) PLATFORM="$1" ;;
    --release) VARIANT="release" ;;
    --debug) VARIANT="debug" ;;
    --install) INSTALL=1 ;;
    --clean) CLEAN=1 ;;
    --skip-checks) SKIP_CHECKS=1 ;;
    -h | --help) usage; exit 0 ;;
    *) die "unknown argument: $1 (try --help)" ;;
  esac
  shift
done
PLATFORM="${PLATFORM:-android}"

(( SKIP_CHECKS )) || run_checks

case "$PLATFORM" in
  android) build_android ;;
  ios) build_ios ;;
  all)
    build_android
    build_ios
    ;;
esac

step "Done in $(( SECONDS - START ))s"
